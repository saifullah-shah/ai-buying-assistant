"""Prompt templates for M4 LLM-grounded recommendation layer.

All templates include explicit grounding instructions so the LLM's output
can be mapped back to M1/M2/M3 data fields (product specs, offer observations,
constraint flags).  No API key needed for design or for the test suite.

Key design principles (D-004, RESEARCH_PROTOCOL.md):
- Every factual claim must be traceable to a source_ref + observed_at
- Unknown fields are marked explicitly, never guessed
- Constraint flags from M3 filtering are restated, not re-interpreted by the LLM
- The LLM explains WHY a candidate fits, what it sacrifices, and what remains unknown
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional

from aba.explanation.grounding import make_evidence_citation


# ---------------------------------------------------------------------------
# Pre-compute display strings (avoid .format() conditionals inside triple-quoted strings)
# ---------------------------------------------------------------------------

def _format_budget_pass(budget_pass: bool, price_amount: float, price_currency: str,
                        budget_amount: float, budget_currency: str) -> str:
    """Pre-compute the budget constraint display string (NO "Budget:" prefix —
    the block template adds it)."""
    budget_status = "passed" if budget_pass else "failed"
    return f"passed — price {price_amount} {price_currency} vs budget {budget_amount} {budget_currency}"


def _format_condition_status(condition_pass: bool, condition: Optional[str],
                             requirement_condition: Optional[str]) -> str:
    """Pre-compute the condition constraint display string (NO leading label)."""
    if requirement_condition is None:
        return "met — no preference specified"
    if condition_pass:
        return f"met — offer condition: {condition}, requirement: {requirement_condition}"
    return f"not met — offer condition: {condition}, requirement: {requirement_condition}"


def _format_must_haves(must_haves_pass: bool, must_haves: Optional[List[str]]) -> str:
    """Pre-compute the must-haves constraint display string (NO leading label)."""
    if must_haves_pass:
        keys = ", ".join(must_haves) if must_haves else "all required"
        return f"satisfied — {keys}"
    keys = ", ".join(must_haves) if must_haves else "none"
    return f"not satisfied — required: {keys}"


def _format_nice_to_haves(nice_score: int, nice_total: int) -> str:
    """Pre-compute the nice-to-haves score display string (NO leading label)."""
    return f"matched: {nice_score}/{nice_total}"


def _format_req_need(need_description: str) -> str:
    # Value only -- the block template already supplies the "Need:" label.
    # Returning a labelled string here produced duplicated output such as
    # "- Need: Need: a laptop for university".
    return need_description


def _format_req_budget(budget_amount: float, budget_currency: str) -> str:
    # Value only; label supplied by REQUIREMENT_SUMMARY_BLOCK.
    return f"{budget_amount} {budget_currency}"


def _format_req_condition(req_condition: Optional[str]) -> str:
    # Value only; label supplied by REQUIREMENT_SUMMARY_BLOCK.
    return req_condition if req_condition else "none specified"


def _format_req_must_haves(must_haves: Optional[List[str]]) -> str:
    # Value only; label supplied by REQUIREMENT_SUMMARY_BLOCK.
    return ", ".join(must_haves) if must_haves else "none"


def _format_req_nice_to_haves(nice_to_haves: Optional[List[str]]) -> str:
    # Value only; label supplied by REQUIREMENT_SUMMARY_BLOCK.
    return ", ".join(nice_to_haves) if nice_to_haves else "none"


# ---------------------------------------------------------------------------
# Prompt building blocks (reusable snippets)
# ---------------------------------------------------------------------------

CONSTRAINT_SUMMARY_BLOCK = """HARD CONSTRAINT COMPLIANCE (from deterministic filtering):
- Budget: {budget_disp}
- Condition: {condition_disp}
- Must-haves: {must_haves_disp}
- Nice-to-haves: {nice_disp}"""


PRODUCT_SUMMARY_BLOCK = """PRODUCT INFORMATION:
- Name: {product_name}
- Product ID: {product_id}
- Specifications:
  {spec_list}
- Source evidence for each spec: {spec_evidence}"""


SPEC_EVIDENCE_BLOCK = """  - {spec_key}: {spec_value} {spec_unit}
    Evidence: {evidence_citation}"""


REQUIREMENT_SUMMARY_BLOCK = """USER REQUIREMENT:
- Need: {need_disp}
- Budget: {budget_disp}
- Condition preference: {condition_disp}
- Must-have specs: {must_haves_disp}
- Nice-to-have specs: {nice_disp}"""


CANDIDATE_CONTEXT_BLOCK = """CANDIDATE {index} of {total}:
{constraint_summary}
{product_summary}
{requirement_summary}"""


# The LLM MUST produce one entry per candidate using exactly the following format.
# These instructions are embedded in the prompt so the LLM knows what structure
# to follow.  They are NOT generated by the prompt — they are directives to the LLM.
# The placeholder {index} will be replaced by the prompt-builder; the LLM fills
# in the rest (FITS BECAUSE, WHAT IT SACRIFICES, UNKNOWN AND WHY, CONSTRAINT COMPLIANCE).
REQUIRED_LLM_SECTIONS = """\
CANDIDATE {index}:
FITS BECAUSE:
  [2-3 sentences.  Reference specific specifications by key name.  If a spec is 
   unknown, explicitly state it is unknown rather than inventing a value.]

WHAT IT SACRIFICES:
  [2-3 sentences.  Explain missing nice-to-haves, price margin, or condition mismatch.  
   If all constraints are met, state "This candidate meets all specified constraints."]

UNKNOWN AND WHY:
  [List each unknown field.  If all fields have known values, state "All specifications 
   have known values."]

CONSTRAINT COMPLIANCE SUMMARY:
- Budget: {budget_status}
- Condition: {condition_status}
- Must-haves: {must_haves_status}
- Nice-to-haves matched: {nice_score}/{nice_total}"""


# ---------------------------------------------------------------------------
# Full prompt template for LLM recommendation
# ---------------------------------------------------------------------------

def make_recommendation_prompt(
    *,
    requirement_description: str,
    budget_amount: float,
    budget_currency: str,
    requirement_condition: Optional[str],
    must_haves: Optional[List[str]],
    nice_to_haves: Optional[List[str]],
    candidates: List[dict],
) -> str:
    """Build the full prompt that will be sent to the LLM.

    Each candidate dict must contain keys derived from the M3 shortlist:
    - product_name, product_id, price_amount, price_currency, condition,
    - budget_pass, condition_pass, must_haves_pass, nice_to_haves_score,
    - nice_to_haves_total, flags (tuple), product_specs (list of dicts with key/value/unit),
    - product_spec_evidence (dict with provider/source_id/note).

    The prompt includes:
    1. The user requirement (M2)
    2. Hard constraint compliance restated from M3 (for LLM context, not re-validation)
    3. Product specification summary with evidence placeholders
    4. Per-candidate context blocks that INSTRUCT the LLM to produce the
       required sections (FITS BECAUSE:/WHAT IT SACRIFICES:/UNKNOWN AND WHY:/CONSTRAINT COMPLIANCE SUMMARY)
    5. Explicit grounding rules (every claim must trace to evidence in the blocks above)
    """
    from aba.explanation.grounding import make_evidence_citation

    # --- Pre-compute requirement display strings ---
    need_disp = _format_req_need(requirement_description)
    budget_disp = _format_req_budget(budget_amount, budget_currency)
    condition_disp = _format_req_condition(requirement_condition)
    must_haves_disp = _format_req_must_haves(must_haves)
    nice_disp = _format_req_nice_to_haves(nice_to_haves)

    # --- Build per-candidate blocks ---
    candidate_blocks = []
    for i, c in enumerate(candidates, start=1):
        # Pre-compute constraint summary for this candidate
        budget_disp_c = _format_budget_pass(
            c.get("budget_pass", False),
            c.get("price_amount", 0),
            c.get("price_currency", ""),
            budget_amount,
            budget_currency,
        )
        condition_disp_c = _format_condition_status(
            c.get("condition_pass", False),
            c.get("condition"),
            requirement_condition,
        )
        must_haves_disp_c = _format_must_haves(
            c.get("must_haves_pass", False),
            c.get("must_haves"),
        )
        nice_disp_c = _format_nice_to_haves(
            c.get("nice_to_haves_score", 0),
            c.get("nice_to_haves_total", 1),
        )

        # Build spec list + evidence
        spec_lines = []
        spec_evidence_lines = []
        for spec in c.get("product_specs", []):
            spec_key = spec.get("key", "")
            spec_value = spec.get("value", "")
            spec_unit = f" {spec.get('unit', '')}" if spec.get("unit") else ""
            # Evidence citation from grounding module
            ev_citation = make_evidence_citation(spec.get("product_spec_evidence"))
            spec_lines.append(f"  - {spec_key}: {spec_value}{spec_unit}")
            spec_evidence_lines.append(f"    Evidence: {ev_citation}")
        spec_summary = "\n".join(spec_lines) if spec_lines else "  (no specifications)"
        evidence_summary = "\n".join(spec_evidence_lines) if spec_evidence_lines else ""

        # Product name and ID
        product_name = c.get("product_name", "Unknown product")
        product_id = c.get("product_id", "unknown")

        # Constraint summary using the block template (labels included in block)
        nice_disp_c = _format_nice_to_haves(
            c.get("nice_to_haves_score", 0),
            c.get("nice_to_haves_total", 1),
        )
        constraint_summary = CONSTRAINT_SUMMARY_BLOCK.format(
            budget_disp=budget_disp_c,
            condition_disp=condition_disp_c,
            must_haves_disp=must_haves_disp_c,
            nice_disp=nice_disp_c,
        )

        # Build the full candidate block — this includes the INSTRUCTION for the LLM
        # to produce the required sections.
        product_summary = PRODUCT_SUMMARY_BLOCK.format(
            product_name=product_name,
            product_id=product_id,
            spec_list=spec_summary,
            spec_evidence=evidence_summary,
        )

        candidate_block = CANDIDATE_CONTEXT_BLOCK.format(
            index=i,
            total=len(candidates),
            constraint_summary=constraint_summary,
            product_summary=product_summary,
            requirement_summary=REQUIREMENT_SUMMARY_BLOCK.format(
                need_disp=need_disp,
                budget_disp=budget_disp,
                condition_disp=condition_disp,
                must_haves_disp=must_haves_disp,
                nice_disp=nice_disp,
            ),
        )
        # Append the LLM instruction block for this candidate using the
        # REQUIRED_LLM_SECTIONS template with the candidate index and all
        # required status values
        candidate_block += "\n" + REQUIRED_LLM_SECTIONS.format(
            index=i,
            budget_status="passed" if c.get("budget_pass", False) else "failed",
            condition_status="met" if c.get("condition_pass", False) else "not met",
            must_haves_status="satisfied" if c.get("must_haves_pass", False) else "not satisfied",
            nice_score=c.get("nice_to_haves_score", 0),
            nice_total=c.get("nice_to_haves_total", 1),
        )
        candidate_blocks.append(candidate_block)

    # Full prompt: embed requirement block at top, then candidate blocks with LLM instructions
    full_prompt = REQUIREMENT_SUMMARY_BLOCK.format(
        need_disp=need_disp,
        budget_disp=budget_disp,
        condition_disp=condition_disp,
        must_haves_disp=must_haves_disp,
        nice_disp=nice_disp,
    )

    full_prompt += "\n\n" + "\n\n".join(candidate_blocks)

    return full_prompt